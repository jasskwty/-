function languageRule(subject: string) {
  if (subject === "english")
    return "المادة لغة إنجليزية: اكتب المحتوى التعليمي والأمثلة بالإنجليزية، وأضف توضيحات قصيرة بالعربي عند الحاجة لتسهيل الفهم.";
  if (subject === "french")
    return "المادة لغة فرنسية: اكتب الأمثلة والمحتوى التعليمي بالفرنسية، والشرح والتوضيح بالعربي المبسط.";
  return "اكتب بالعربية الفصحى المبسطة الواضحة، ومسموح تستخدم كلمات كويتية خفيفة للتقريب. المصطلحات العلمية اكتبها بالعربي ومعها المصطلح الإنجليزي بين قوسين أول مرة.";
}

