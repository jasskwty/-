import { UserFacingError } from "./claude";
import type Anthropic from "@anthropic-ai/sdk";

export const MAX_TEXT = 20000;
const MAX_IMAGE_B64 = 7_000_000; // تقريباً ٥ ميغابايت
const MAX_PDF_B64 = 14_000_000; // تقريباً ١٠ ميغابايت
const MAX_REFERENCE = 30000;
const MAX_IMAGES = 4;

// ===== التحقق من المدخلات =====

export function readContext(body: Record<string, unknown>): StudyContext {
  const grade = GRADES.find((g) => g.id === body.grade);
  const subject = SUBJECTS.find((s) => s.id === body.subject);
  if (!grade || !subject) throw new UserFacingError("اختر الصف والمادة أول.");
  const role = body.role === "teacher" ? "teacher" : "student";
  const reference = role === "teacher" ? readText(body.reference, "مرجع المنهج", { required: false, max: MAX_REFERENCE }) : "";
  return { grade: grade.id, subject: subject.id, role, reference };
}

export function readText(v: unknown, label: string, { required = true, max = MAX_TEXT } = {}): string {
  const s = typeof v === "string" ? v.trim() : "";
  if (required && !s) throw new UserFacingError(`اكتب ${label} أول.`);
  if (s.length > max) throw new UserFacingError(`${label} طويل جداً (الحد ${max.toLocaleString("ar")} حرف).`);
  return s;
}

export function readImages(v: unknown, max = MAX_IMAGES): ImageData[] {
  if (v == null) return [];
  if (!Array.isArray(v)) throw new UserFacingError("صيغة المرفقات غير صحيحة.");
  if (v.length > max) throw new UserFacingError(`تقدر ترفع ${max} مرفقات كحد أقصى.`);
  return v.map((img) => {
    const media_type = (img as ImageData)?.media_type;
    const data = (img as ImageData)?.data;
    const isPdf = media_type === PDF_TYPE;
    if ((!isPdf && !(ALLOWED_IMAGE_TYPES as readonly string[]).includes(media_type)) || typeof data !== "string" || !data)
      throw new UserFacingError("نوع الملف غير مدعوم. استخدم صورة (JPG أو PNG أو WEBP) أو ملف PDF.");
    if (data.length > (isPdf ? MAX_PDF_B64 : MAX_IMAGE_B64))
      throw new UserFacingError(isPdf ? "ملف PDF كبير جداً (الحد ١٠ ميغابايت)." : "الصورة كبيرة جداً. جرّب صورة أصغر.");
    return { media_type, data };
  });
}

export function readInt(v: unknown, min: number, max: number, fallback: number) {
  const n = Math.round(Number(v));
  return Number.isFinite(n) ? Math.min(max, Math.max(min, n)) : fallback;
}

export async function readBody(req: Request): Promise<Record<string, unknown>> {
  try {
    const b = await req.json();
    if (b && typeof b === "object") return b as Record<string, unknown>;
  } catch {}
  throw new UserFacingError("الطلب غير صالح.");
}

export function userContent(text: string, images: ImageData[]): Anthropic.Beta.BetaContentBlockParam[] {
  return [
    ...images.map((img): Anthropic.Beta.BetaContentBlockParam =>
      img.media_type === PDF_TYPE
        ? { type: "document", source: { type: "base64", media_type: PDF_TYPE, data: img.data } }
        : { type: "image", source: { type: "base64", media_type: img.media_type, data: img.data } },
    ),
    { type: "text" as const, text },
  ];
}

